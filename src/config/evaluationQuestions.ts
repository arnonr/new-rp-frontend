/**
 * เลือกชุดคำถามที่เหมาะสมตามข้อมูลของ Paper (ปี และ ประเภทโครงการ)
 */
export const getQuestionsByPaper = (paper: any): QuestionGroup[] => {
  if (!paper) {
    return questions_2570_general;
  }

  const runningYear = Number(paper.running_year);
  const rpNo = String(paper.rp_no || "");

  // ตรวจสอบว่าเป็นโครงการปี 2569 หรือไม่
  if (runningYear === 69 || runningYear === 2569 || rpNo.includes("sci-69")) {
    return questions_2569;
  }

  // สำหรับปี 2570 (หรือปีปัจจุบัน/อนาคต) ตรวจสอบประเภทโครงการ
  const paperTypeName = paper.paper_type?.name || "";
  if (paperTypeName.includes("บูรณาการ")) {
    return questions_2570_integrated;
  }

  return questions_2570_general;
};
